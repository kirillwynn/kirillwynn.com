def test_prepare_is_deterministic_idempotent_and_refuses_changed_output(tmp_path):
    specs = [
        ("animated", "animated.gif", gif_bytes(), "animated"),
        ("static", "static.png", png_bytes(metadata=True), "static"),
        ("webp", "webp.png", webp_bytes(), "static"),
    ]
    manifest, source_root, _ = write_manifest(tmp_path, specs)
    first = tmp_path / "first"
    second = tmp_path / "second"
    path_one, digest_one, attestation_one = prepare_catalog(
        manifest_path=manifest,
        source_root=source_root,
        output_root=first,
    )
    path_again, digest_again, _ = prepare_catalog(
        manifest_path=manifest,
        source_root=source_root,
        output_root=first,
    )
    path_two, digest_two, attestation_two = prepare_catalog(
        manifest_path=manifest,
        source_root=source_root,
        output_root=second,
    )

    assert digest_one == digest_again == digest_two
    assert path_one.read_bytes() == path_again.read_bytes() == path_two.read_bytes()
    assert attestation_one == attestation_two
    for item in attestation_one["items"]:
        for label in ("asset", "poster"):
            if item[label]:
                assert (
                    first.joinpath(item[label]["relative_path"]).read_bytes()
                    == second.joinpath(item[label]["relative_path"]).read_bytes()
                )
    object_path = first / attestation_one["items"][0]["asset"]["relative_path"]
    object_path.write_bytes(b"changed")
    with pytest.raises(CatalogPipelineError, match="Refusing to overwrite"):
        prepare_catalog(
            manifest_path=manifest,
            source_root=source_root,
            output_root=first,
        )


class FakeObjectStore:
    def __init__(self, environment="staging"):
        self.environment = environment
        self.prefix = f"{environment}/media"
        self.objects = {}
        self.put_calls = 0

    def put_if_absent(self, item, *, catalog_id, version):
        self.put_calls += 1
        self.objects.setdefault(
            item.storage_key,
            (item.body, item.content_type, item.sha256, catalog_id, version),
        )

    def verify(self, item, *, catalog_id, version):
        assert self.objects[item.storage_key] == (
            item.body,
            item.content_type,
            item.sha256,
            catalog_id,
            version,
        )


