def test_prepare_rejects_symlink_and_source_hash_mismatch(tmp_path):
    body = png_bytes()
    manifest, source_root, document = write_manifest(
        tmp_path, [("first", "first.png", body, "static")]
    )
    (source_root / "first.png").write_bytes(png_bytes(size=(15, 15)))
    with pytest.raises(CatalogPipelineError, match="source SHA-256 mismatch"):
        prepare_catalog(
            manifest_path=manifest,
            source_root=source_root,
            output_root=tmp_path / "bad-hash",
        )

    (source_root / "first.png").unlink()
    target = source_root / "actual.png"
    target.write_bytes(body)
    (source_root / "first.png").symlink_to(target)
    document["items"][0]["source_sha256"] = sha256(body)
    manifest.write_text(json.dumps(document, indent=2, sort_keys=True) + "\n")
    with pytest.raises(CatalogPipelineError, match="Symlinks are forbidden"):
        prepare_catalog(
            manifest_path=manifest,
            source_root=source_root,
            output_root=tmp_path / "symlink",
        )


