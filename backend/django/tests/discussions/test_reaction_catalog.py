def test_s3_store_uses_isolated_prefix_immutable_headers_and_checksums():
    body = b"attested bytes"
    digest = sha256(body)
    item = PreparedObject(
        relative_path="objects/reactions/test/" + digest + "/asset.webp",
        storage_key="reactions/test/" + digest + "/asset.webp",
        sha256=digest,
        size=len(body),
        content_type="image/webp",
        body=body,
    )
    storage = FakeS3Storage("staging/media")
    store = S3ReactionObjectStore(storage, environment="staging")
    store.put_if_absent(item, catalog_id="test", version=f"sha256-{digest}")
    store.verify(item, catalog_id="test", version=f"sha256-{digest}")
    uploaded = storage.client.objects[f"staging/media/{item.storage_key}"]

    assert uploaded["ContentType"] == "image/webp"
    assert uploaded["CacheControl"] == "public, max-age=31536000, immutable"
    assert uploaded["Metadata"] == {
        "sha256": digest,
        "catalog-id": "test",
        "asset-version": f"sha256-{digest}",
    }
    assert uploaded["ChecksumSHA256"] == base64.b64encode(bytes.fromhex(digest)).decode()
    store.put_if_absent(item, catalog_id="test", version=f"sha256-{digest}")
    assert len(storage.client.objects) == 1
    with pytest.raises(CatalogPipelineError, match="not isolated"):
        S3ReactionObjectStore(storage, environment="production")


