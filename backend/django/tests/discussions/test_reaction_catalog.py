def sha256(value):
    return hashlib.sha256(value).hexdigest()


def png_bytes(*, size=(16, 16), metadata=False):
    image = Image.new("RGBA", size, (220, 30, 80, 180))
    output = io.BytesIO()
    options = {}
    if metadata:
        info = PngImagePlugin.PngInfo()
        info.add_text("Software", "must disappear")
        info.add_itxt("XML:com.adobe.xmp", "<xmp>must disappear</xmp>")
        options["pnginfo"] = info
    image.save(output, "PNG", **options)
    image.close()
    return output.getvalue()


def webp_bytes(*, size=(16, 16)):
    image = Image.new("RGBA", size, (20, 100, 220, 160))
    output = io.BytesIO()
    image.save(output, "WEBP", lossless=True, method=6, exact=True)
    image.close()
    return output.getvalue()


def gif_bytes(*, delays=(0, 10, 40), size=(16, 16), comment=b"must disappear"):
    frames = [
        Image.new("RGBA", size, (index * 60, 30, 240 - index * 50, 180))
        for index in range(len(delays))
    ]
    output = io.BytesIO()
    frames[0].save(
        output,
        "GIF",
        save_all=True,
        append_images=frames[1:],
        duration=list(delays),
        loop=0,
        disposal=2,
        comment=comment,
    )
    for frame in frames:
        frame.close()
    return output.getvalue()


def manifest_document(specs, *, approval_scope="staging-only/unverified"):
    specs = list(specs)
    while len(specs) < 3:
        index = len(specs) + 1
        specs.append((f"fixture-{index}", f"fixture-{index}.png", png_bytes(), "static"))
    items = []
    for index, (catalog_id, source_path, body, kind) in enumerate(specs, start=1):
        items.append(
            {
                "catalog_id": catalog_id,
                "source_path": source_path,
                "source_sha256": sha256(body),
                "display_name": catalog_id.replace("-", " ").title(),
                "accessibility_label": f"{catalog_id} reaction",
                "kind": kind,
                "ordering": index * 10,
                "enabled": True,
                "selectable": True,
                "quick_order": index if index <= 3 else None,
                "provenance": {
                    "source": "Synthetic test fixture",
                    "author": "Test suite",
                },
                "license": "Synthetic fixture",
                "rights_basis": "Generated by the test suite",
                "approval_status": approval_scope,
                "immutable_asset_version": f"source-sha256-{sha256(body)}",
            }
        )
    return {
        "schema_version": 1,
        "catalog_id": "test-catalog",
        "catalog_version": "test-v1",
        "approval_scope": approval_scope,
        "quick_reactions": [item["catalog_id"] for item in items[:3]],
        "items": items,
    }


def write_manifest(tmp_path, specs, *, approval_scope="staging-only/unverified"):
    source_root = tmp_path / "source"
    source_root.mkdir(parents=True)
    document = manifest_document(specs, approval_scope=approval_scope)
    bodies = {spec[1]: spec[2] for spec in specs}
    for item in document["items"]:
        body = bodies.get(item["source_path"], png_bytes())
        path = source_root / item["source_path"]
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(body)
        item["source_sha256"] = sha256(body)
        item["immutable_asset_version"] = f"source-sha256-{sha256(body)}"
    manifest = tmp_path / "manifest.json"
    manifest.write_text(json.dumps(document, indent=2, sort_keys=True, ensure_ascii=False) + "\n")
    return manifest, source_root, document


def prepare(tmp_path, specs):
    manifest, source_root, _ = write_manifest(tmp_path, specs)
    output = tmp_path / "prepared"
    attestation_path, digest, attestation = prepare_catalog(
        manifest_path=manifest,
        source_root=source_root,
        output_root=output,
    )
    return manifest, source_root, output, attestation_path, digest, attestation


