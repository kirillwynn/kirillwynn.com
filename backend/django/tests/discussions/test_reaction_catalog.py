def test_animation_delays_loop_poster_and_comment_normalization(tmp_path):
    animation = gif_bytes(delays=(0, 10, 40))
    _, _, _, attestation_path, _, attestation = prepare(
        tmp_path,
        [
            ("animated", "animated.gif", animation, "animated"),
            ("second", "second.png", png_bytes(), "static"),
            ("third", "third.png", png_bytes(), "static"),
        ],
    )
    item = attestation["items"][0]
    asset = attestation_path.parent / item["asset"]["relative_path"]
    poster = attestation_path.parent / item["poster"]["relative_path"]

    with Image.open(asset) as normalized:
        delays = [frame.info["duration"] for frame in ImageSequence.Iterator(normalized)]
        assert normalized.info["loop"] == 0
        assert min(delays) >= 20
        assert sum(delays) == item["duration_ms"]
        assert "comment" not in {str(key).lower() for key in normalized.info}
    with Image.open(poster) as normalized_poster:
        assert normalized_poster.format == "WEBP"
        assert getattr(normalized_poster, "n_frames", 1) == 1
    assert item["poster"]["sha256"] == sha256(poster.read_bytes())
    assert item["poster"]["storage_key"].split("/")[2] == item["asset"]["sha256"]


